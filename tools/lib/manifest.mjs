// The skills manifest: a list of every skill, every file inside it, and each
// file's size and SHA-256. An agent (or the installer) downloads this list
// first, then downloads only the files it names and checks each one.
//
// The manifest proves a download is complete and not corrupted. It does not
// prove the repository itself is trustworthy: it is served from the same place
// as the files.

import fs from 'node:fs';
import path from 'node:path';
import { toPosix, walkFiles } from './fs-utils.mjs';
import { fingerprint } from './content-hash.mjs';

export const MANIFEST_NAME = 'skills-manifest.json';
export const MANIFEST_SCHEMA = 1;
export const REPOSITORY_URL = 'https://github.com/vijetarajput/vyson-web-skills';
export const RAW_BASE_URL = 'https://raw.githubusercontent.com/vijetarajput/vyson-web-skills';

// Safety limits. The real skills are far below them.
export const MAX_FILE_BYTES = 2_000_000;
export const MAX_FILES_PER_SKILL = 200;

const SKIP_NAMES = new Set(['.DS_Store', 'Thumbs.db']);
const SKILL_NAME = /^[a-z0-9]+(-[a-z0-9]+)*$/;

/** Is this a valid skill folder name (lowercase letters, numbers, single hyphens, max 64)? */
export function isValidSkillName(name) {
  return typeof name === 'string' && name.length > 0 && name.length <= 64 && SKILL_NAME.test(name);
}

/**
 * Is this a safe relative file path (no "..", no absolute path, no backslash,
 * no drive letter, no empty parts)?
 */
export function isSafeRelativePath(p) {
  if (typeof p !== 'string' || p.length === 0 || p.length > 200) return false;
  if (p.includes('\\') || p.includes(':') || p.includes('\0') || p.startsWith('/')) return false;
  return p.split('/').every((part) => part !== '' && part !== '.' && part !== '..');
}

/**
 * Build the manifest for every skill folder inside `skillsDir`.
 * The result is deterministic: no dates, sorted lists.
 * @param {string} skillsDir
 * @param {{ order?: string[] }} [opts]  skills listed here come first, in this order
 */
export function buildManifest(skillsDir, opts = {}) {
  const names = fs
    .readdirSync(skillsDir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith('.'))
    .filter((e) => fs.existsSync(path.join(skillsDir, e.name, 'SKILL.md')))
    .map((e) => e.name)
    .sort();
  const first = (opts.order ?? []).filter((n) => names.includes(n));
  const ordered = [...first, ...names.filter((n) => !first.includes(n))];

  const skills = {};
  for (const name of ordered) {
    const dir = path.join(skillsDir, name);
    const files = walkFiles(dir, { ignoreDirNames: ['.git', 'node_modules'] })
      .filter((f) => !SKIP_NAMES.has(path.basename(f)))
      .map((f) => {
        const rel = toPosix(path.relative(dir, f));
        const { sha256, bytes } = fingerprint(fs.readFileSync(f), rel);
        return { path: rel, bytes, sha256 };
      })
      .sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
    skills[name] = { files };
  }
  return {
    schema: MANIFEST_SCHEMA,
    repository: REPOSITORY_URL,
    note: 'Generated by tools/build-manifest.mjs. Do not edit by hand. sha256 is taken after Windows line endings (CRLF) are changed to LF in text files.',
    order: ordered,
    skills,
  };
}

/** The manifest as the exact text that is written to disk. */
export function manifestToText(manifest) {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

/**
 * Check that a parsed manifest has the expected shape and only safe values.
 * Never throws. Everything downloaded from the network goes through this first.
 * @returns {{ ok: true } | { ok: false, error: string }}
 */
export function validateManifest(m) {
  const bad = (error) => ({ ok: false, error: `The skills manifest is not usable: ${error}` });
  if (!m || typeof m !== 'object' || Array.isArray(m)) return bad('it is not a JSON object.');
  if (m.schema !== MANIFEST_SCHEMA) return bad(`unsupported schema ${JSON.stringify(m.schema)} (expected ${MANIFEST_SCHEMA}).`);
  if (!m.skills || typeof m.skills !== 'object' || Array.isArray(m.skills)) return bad('"skills" is missing.');
  if (!Array.isArray(m.order)) return bad('"order" is missing.');
  const names = Object.keys(m.skills);
  if (names.length === 0) return bad('it lists no skills.');
  for (const n of m.order) {
    if (!names.includes(n)) return bad(`"order" names "${n}", which is not a listed skill.`);
  }
  for (const name of names) {
    if (!isValidSkillName(name)) return bad(`"${name}" is not a valid skill name.`);
    const files = m.skills[name]?.files;
    if (!Array.isArray(files) || files.length === 0) return bad(`skill "${name}" lists no files.`);
    if (files.length > MAX_FILES_PER_SKILL) return bad(`skill "${name}" lists too many files (${files.length}).`);
    const seen = new Set();
    for (const f of files) {
      if (!f || typeof f !== 'object') return bad(`skill "${name}" has a file entry that is not an object.`);
      if (!isSafeRelativePath(f.path)) return bad(`skill "${name}" has an unsafe file path: ${JSON.stringify(f.path)}.`);
      if (seen.has(f.path)) return bad(`skill "${name}" lists "${f.path}" twice.`);
      seen.add(f.path);
      if (!Number.isInteger(f.bytes) || f.bytes < 0 || f.bytes > MAX_FILE_BYTES) {
        return bad(`skill "${name}" file "${f.path}" has an invalid size.`);
      }
      if (typeof f.sha256 !== 'string' || !/^[0-9a-f]{64}$/.test(f.sha256)) {
        return bad(`skill "${name}" file "${f.path}" has an invalid sha256.`);
      }
    }
    if (!seen.has('SKILL.md')) return bad(`skill "${name}" does not list SKILL.md.`);
  }
  return { ok: true };
}

/**
 * Compare a skills folder on disk with the manifest.
 * @param {string} skillsDir
 * @param {object} manifest  a validated manifest
 * @param {string[]} [names] skills to check (default: all in the manifest)
 * @returns {{ missing: string[], changed: string[], extra: string[] }}  "skill/path" entries
 */
export function compareWithManifest(skillsDir, manifest, names) {
  const missing = [];
  const changed = [];
  const extra = [];
  for (const name of names ?? Object.keys(manifest.skills)) {
    const dir = path.join(skillsDir, name);
    const listed = new Map(manifest.skills[name].files.map((f) => [f.path, f]));
    const onDisk = new Map();
    if (fs.existsSync(dir)) {
      for (const f of walkFiles(dir, { ignoreDirNames: ['.git', 'node_modules'] })) {
        if (SKIP_NAMES.has(path.basename(f))) continue;
        onDisk.set(toPosix(path.relative(dir, f)), f);
      }
    }
    for (const [rel, entry] of listed) {
      const file = onDisk.get(rel);
      if (!file) {
        missing.push(`${name}/${rel}`);
        continue;
      }
      const fp = fingerprint(fs.readFileSync(file), rel);
      if (fp.sha256 !== entry.sha256 || fp.bytes !== entry.bytes) changed.push(`${name}/${rel}`);
    }
    for (const rel of onDisk.keys()) if (!listed.has(rel)) extra.push(`${name}/${rel}`);
  }
  return { missing, changed, extra };
}
